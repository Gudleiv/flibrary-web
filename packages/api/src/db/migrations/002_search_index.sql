-- Собственный поисковый индекс.
--
-- Зачем он нужен, когда в коллекции уже есть FTS: её индексы созданы с дефолтным
-- токенизатором unicode61, то есть без морфологии («города» не находит «город»),
-- разнесены по четырём таблицам (название, авторы, серия, аннотация) и не позволяют
-- ранжировать по bm25 при пересечении предикатов. Здесь — одна таблица со всеми
-- текстовыми полями, по основам слов.
--
-- Таблицы создаются пустыми; наполняет их индексатор (src/indexer).

CREATE VIRTUAL TABLE books_fts USING fts5(
    title,
    authors,
    series,
    keywords,
    annotation,
    tokenize = 'unicode61 remove_diacritics 2'
);

-- Подстрочный поиск: триграммы позволяют искать «орол» внутри «Королевство».
-- Отдельная таблица, потому что токенизатор задаётся на всю таблицу целиком.
-- Колонки те же, что и в books_fts (кроме аннотации — она слишком объёмна для триграмм),
-- чтобы предикат по конкретному полю не превращался в поиск по всему.
CREATE VIRTUAL TABLE books_trgm USING fts5(
    title,
    authors,
    series,
    keywords,
    tokenize = 'trigram'
);
